-- OrderFlow PostgreSQL design contract.
-- Target: standard PostgreSQL 17+, no extension required.
-- Apply to an empty development database; this is not an upgrade migration.
-- Business state transitions and immutable-record permissions must be implemented
-- and integration tested. This file alone does not enforce the worker protocol.
CREATE SCHEMA orderflow;

CREATE TABLE orderflow.tenants (
    tenant_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    currency char(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE orderflow.sources (
    tenant_id uuid NOT NULL REFERENCES orderflow.tenants(tenant_id),
    source_id uuid NOT NULL DEFAULT gen_random_uuid(),
    name text NOT NULL,
    connector_type text NOT NULL CHECK (connector_type IN ('api', 'events', 'csv')),
    enabled boolean NOT NULL DEFAULT true,
    PRIMARY KEY (tenant_id, source_id),
    UNIQUE (tenant_id, name)
);

CREATE TABLE orderflow.source_authorities (
    tenant_id uuid NOT NULL,
    entity_type text NOT NULL CHECK (entity_type IN ('product', 'order')),
    source_id uuid NOT NULL,
    PRIMARY KEY (tenant_id, entity_type),
    UNIQUE (tenant_id, entity_type, source_id),
    FOREIGN KEY (tenant_id, source_id) REFERENCES orderflow.sources(tenant_id, source_id)
);

CREATE TABLE orderflow.ingestion_runs (
    tenant_id uuid NOT NULL,
    run_id uuid NOT NULL DEFAULT gen_random_uuid(),
    source_id uuid NOT NULL,
    status text NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'running', 'succeeded', 'failed')),
    interval_start timestamptz NOT NULL,
    interval_end timestamptz NOT NULL,
    started_at timestamptz,
    finished_at timestamptz,
    failure_code text,
    PRIMARY KEY (tenant_id, run_id),
    FOREIGN KEY (tenant_id, source_id) REFERENCES orderflow.sources(tenant_id, source_id),
    CHECK (interval_end > interval_start),
    CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at)
);

CREATE TABLE orderflow.processing_partitions (
    tenant_id uuid NOT NULL,
    source_id uuid NOT NULL,
    partition_key text NOT NULL CHECK (octet_length(partition_key) BETWEEN 1 AND 128),
    committed_count bigint NOT NULL DEFAULT 0 CHECK (committed_count >= 0),
    last_committed_event_id uuid,
    last_commit_at timestamptz,
    PRIMARY KEY (tenant_id, source_id, partition_key),
    FOREIGN KEY (tenant_id, source_id) REFERENCES orderflow.sources(tenant_id, source_id),
    CHECK ((committed_count = 0 AND last_committed_event_id IS NULL)
        OR (committed_count > 0 AND last_committed_event_id IS NOT NULL))
);

CREATE TABLE orderflow.inbox_events (
    tenant_id uuid NOT NULL,
    event_id uuid NOT NULL DEFAULT gen_random_uuid(),
    inbox_sequence bigint GENERATED BY DEFAULT AS IDENTITY,
    source_id uuid NOT NULL,
    source_event_id text NOT NULL CHECK (length(source_event_id) BETWEEN 1 AND 200),
    partition_key text NOT NULL,
    schema_version text NOT NULL CHECK (schema_version = '1'),
    entity_type text NOT NULL CHECK (entity_type IN ('product', 'order')),
    entity_id text NOT NULL CHECK (length(entity_id) BETWEEN 1 AND 200),
    entity_version bigint NOT NULL CHECK (entity_version > 0),
    effective_at timestamptz NOT NULL,
    occurred_at timestamptz NOT NULL,
    ingested_at timestamptz NOT NULL DEFAULT now(),
    payload jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    payload_sha256 char(64) NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    envelope_sha256 char(64) NOT NULL CHECK (envelope_sha256 ~ '^[0-9a-f]{64}$'),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'retry_wait', 'completed', 'quarantined')),
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    available_at timestamptz NOT NULL DEFAULT now(),
    last_error_code text,
    PRIMARY KEY (tenant_id, event_id),
    UNIQUE (tenant_id, source_id, source_event_id),
    UNIQUE (tenant_id, source_id, partition_key, event_id),
    UNIQUE (tenant_id, event_id, source_id, entity_type, entity_id, entity_version),
    FOREIGN KEY (tenant_id, source_id, partition_key)
        REFERENCES orderflow.processing_partitions(tenant_id, source_id, partition_key)
);

CREATE INDEX inbox_eligible_idx ON orderflow.inbox_events
    (tenant_id, source_id, partition_key, available_at, inbox_sequence)
    WHERE status IN ('pending', 'retry_wait');

ALTER TABLE orderflow.processing_partitions ADD CONSTRAINT checkpoint_event_scope_fk
    FOREIGN KEY (tenant_id, source_id, partition_key, last_committed_event_id)
    REFERENCES orderflow.inbox_events(tenant_id, source_id, partition_key, event_id);

CREATE TABLE orderflow.entity_revisions (
    tenant_id uuid NOT NULL,
    entity_type text NOT NULL CHECK (entity_type IN ('product', 'order')),
    entity_id text NOT NULL,
    entity_version bigint NOT NULL CHECK (entity_version > 0),
    source_id uuid NOT NULL,
    event_id uuid NOT NULL,
    effective_at timestamptz NOT NULL,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    payload_sha256 char(64) NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    payload jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    PRIMARY KEY (tenant_id, entity_type, entity_id, entity_version),
    UNIQUE (tenant_id, event_id),
    FOREIGN KEY (tenant_id, entity_type, source_id)
        REFERENCES orderflow.source_authorities(tenant_id, entity_type, source_id),
    FOREIGN KEY (tenant_id, event_id, source_id, entity_type, entity_id, entity_version)
        REFERENCES orderflow.inbox_events
        (tenant_id, event_id, source_id, entity_type, entity_id, entity_version)
);

CREATE TABLE orderflow.entity_current (
    tenant_id uuid NOT NULL,
    entity_type text NOT NULL,
    entity_id text NOT NULL,
    entity_version bigint NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, entity_type, entity_id),
    FOREIGN KEY (tenant_id, entity_type, entity_id, entity_version)
        REFERENCES orderflow.entity_revisions(tenant_id, entity_type, entity_id, entity_version)
);

CREATE VIEW orderflow.current_entities WITH (security_invoker=true) AS
SELECT r.tenant_id, r.entity_type, r.entity_id, r.entity_version,
       r.source_id, r.event_id, r.effective_at, r.payload,
       c.updated_at
FROM orderflow.entity_current c
JOIN orderflow.entity_revisions r USING (tenant_id, entity_type, entity_id, entity_version);

CREATE TABLE orderflow.processing_receipts (
    tenant_id uuid NOT NULL,
    event_id uuid NOT NULL,
    outcome text NOT NULL CHECK (outcome IN
        ('applied_current', 'history_only', 'duplicate_revision', 'quarantined')),
    reason_code text,
    committed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, event_id),
    FOREIGN KEY (tenant_id, event_id) REFERENCES orderflow.inbox_events(tenant_id, event_id),
    CHECK (outcome <> 'quarantined' OR reason_code IS NOT NULL)
);

CREATE TABLE orderflow.quarantines (
    tenant_id uuid NOT NULL,
    quarantine_id uuid NOT NULL DEFAULT gen_random_uuid(),
    event_id uuid NOT NULL,
    reason_code text NOT NULL,
    redacted_details jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz,
    PRIMARY KEY (tenant_id, quarantine_id),
    FOREIGN KEY (tenant_id, event_id) REFERENCES orderflow.inbox_events(tenant_id, event_id),
    CHECK (resolved_at IS NULL OR resolved_at >= created_at)
);

CREATE TABLE orderflow.connector_cursors (
    tenant_id uuid NOT NULL,
    source_id uuid NOT NULL,
    cursor_name text NOT NULL,
    cursor_value jsonb NOT NULL,
    cursor_revision bigint NOT NULL DEFAULT 1 CHECK (cursor_revision > 0),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, source_id, cursor_name),
    FOREIGN KEY (tenant_id, source_id) REFERENCES orderflow.sources(tenant_id, source_id)
);

CREATE TABLE orderflow.quality_results (
    tenant_id uuid NOT NULL,
    check_id uuid NOT NULL DEFAULT gen_random_uuid(),
    run_id uuid NOT NULL,
    check_name text NOT NULL,
    status text NOT NULL CHECK (status IN ('pass', 'fail', 'error')),
    observed numeric,
    expected numeric,
    checked_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, check_id),
    FOREIGN KEY (tenant_id, run_id) REFERENCES orderflow.ingestion_runs(tenant_id, run_id)
);

CREATE TABLE orderflow.operator_audit (
    tenant_id uuid NOT NULL REFERENCES orderflow.tenants(tenant_id),
    audit_id uuid NOT NULL DEFAULT gen_random_uuid(),
    actor_subject text NOT NULL,
    action text NOT NULL,
    target_type text NOT NULL,
    target_id text NOT NULL,
    reason text NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, audit_id)
);

