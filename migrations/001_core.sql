CREATE FUNCTION orderflow.immutable_record() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,orderflow AS $$
BEGIN
    RAISE EXCEPTION 'Immutable record requires a new identity/version' USING ERRCODE='23514';
END $$;
CREATE TRIGGER immutable_revision BEFORE UPDATE OR DELETE ON orderflow.entity_revisions
FOR EACH ROW EXECUTE FUNCTION orderflow.immutable_record();
CREATE TRIGGER immutable_receipt BEFORE UPDATE OR DELETE ON orderflow.processing_receipts
FOR EACH ROW EXECUTE FUNCTION orderflow.immutable_record();
CREATE TRIGGER immutable_audit BEFORE UPDATE OR DELETE ON orderflow.operator_audit
FOR EACH ROW EXECUTE FUNCTION orderflow.immutable_record();
CREATE TRIGGER immutable_quality BEFORE UPDATE OR DELETE ON orderflow.quality_results
FOR EACH ROW EXECUTE FUNCTION orderflow.immutable_record();

CREATE FUNCTION orderflow.guard_inbox() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,orderflow AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'Inbox deletion is forbidden' USING ERRCODE='23514';
    END IF;
    IF (to_jsonb(NEW)-ARRAY['status','attempt_count','available_at','last_error_code'])
       IS DISTINCT FROM
       (to_jsonb(OLD)-ARRAY['status','attempt_count','available_at','last_error_code']) THEN
        RAISE EXCEPTION 'Inbox semantic content is immutable' USING ERRCODE='23514';
    END IF;
    IF OLD.status IN('completed','quarantined') AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'Terminal inbox state is immutable' USING ERRCODE='23514';
    END IF;
    IF NEW.attempt_count < OLD.attempt_count THEN
        RAISE EXCEPTION 'Attempt history cannot decrease' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_inbox BEFORE UPDATE OR DELETE ON orderflow.inbox_events
FOR EACH ROW EXECUTE FUNCTION orderflow.guard_inbox();

CREATE FUNCTION orderflow.guard_current() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,orderflow AS $$
BEGIN
    IF NEW.entity_version <= OLD.entity_version THEN
        RAISE EXCEPTION 'Current version must strictly increase' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER monotonic_current BEFORE UPDATE ON orderflow.entity_current
FOR EACH ROW EXECUTE FUNCTION orderflow.guard_current();

CREATE FUNCTION orderflow.check_terminal_receipt() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,orderflow AS $$
DECLARE s text; o text;
BEGIN
    SELECT status INTO s FROM orderflow.inbox_events
      WHERE tenant_id=NEW.tenant_id AND event_id=NEW.event_id;
    SELECT outcome INTO o FROM orderflow.processing_receipts
      WHERE tenant_id=NEW.tenant_id AND event_id=NEW.event_id;
    IF (s IN('completed','quarantined')) IS DISTINCT FROM (o IS NOT NULL)
       OR (s='quarantined') IS DISTINCT FROM coalesce(o='quarantined',false) THEN
        RAISE EXCEPTION 'Inbox terminal status and receipt must commit together' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER terminal_inbox_receipt AFTER INSERT OR UPDATE ON orderflow.inbox_events
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION orderflow.check_terminal_receipt();
CREATE CONSTRAINT TRIGGER terminal_receipt_inbox AFTER INSERT ON orderflow.processing_receipts
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION orderflow.check_terminal_receipt();

CREATE FUNCTION orderflow.resolve_source(key_hash text, requested_source uuid)
RETURNS TABLE(tenant_id uuid,source_id uuid)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,orderflow AS $$
DECLARE resolved_tenant uuid; resolved_source uuid;
BEGIN
    SELECT c.tenant_id,c.source_id INTO resolved_tenant,resolved_source
      FROM orderflow.source_credentials c
      WHERE c.key_sha256=key_hash AND c.source_id=requested_source AND c.active;
    IF resolved_tenant IS NULL THEN RETURN; END IF;
    PERFORM set_config('orderflow.tenant_id',resolved_tenant::text,true);
    RETURN QUERY SELECT s.tenant_id,s.source_id FROM orderflow.sources s
      WHERE s.tenant_id=resolved_tenant AND s.source_id=resolved_source AND s.enabled;
END $$;
CREATE FUNCTION orderflow.resolve_member(requested_issuer text,requested_subject text,requested_tenant uuid)
RETURNS TABLE(tenant_id uuid,subject text,role text)
LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,orderflow AS $$
    SELECT m.tenant_id,m.subject,m.role FROM orderflow.memberships m
      WHERE m.issuer=requested_issuer AND m.subject=requested_subject AND m.active
      AND (requested_tenant IS NULL OR m.tenant_id=requested_tenant)
$$;
CREATE FUNCTION orderflow.fixture_member(requested_alias text)
RETURNS TABLE(tenant_id uuid,subject text,role text,issuer text,fixture_alias text)
LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,orderflow AS $$
    SELECT m.tenant_id,m.subject,m.role,m.issuer,m.fixture_alias
      FROM orderflow.memberships m WHERE m.fixture_alias=requested_alias AND m.active
$$;
